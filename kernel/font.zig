const box = [height]*const [width]u8{ "#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####" };

/// Is pixel (x, y) of character c set?
pub fn pixel(c: u8, x: usize, y: usize) bool {
    var rows = box;
    for (art) |g| {
        if (g.char == c) {
            rows = g.rows;
            break;
        }
    }
    return rows[y][x] == '#';
}
